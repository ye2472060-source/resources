const { chromium } = require("playwright");
const path = require("path");
(async () => {
  const browser = await chromium.launch();
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  const file = "file:///" + path.join(__dirname, "..", "index.html").replace(/\\/g, "/").replace(/^([A-Za-z]):/, "$1:");
  await page.goto(file, { waitUntil: "load" });
  await page.waitForTimeout(400);
  await page.click('#nav a[href="#/m/m7"]');
  await page.waitForTimeout(400);
  await page.screenshot({ path: path.join(__dirname, "test-module.png") });
  await page.click('#nav a[href="#/library"]');
  await page.waitForTimeout(400);
  await page.screenshot({ path: path.join(__dirname, "test-library.png") });
  await page.click('#nav a[href="#/project"]');
  await page.waitForTimeout(400);
  await page.screenshot({ path: path.join(__dirname, "test-project.png") });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto(file, { waitUntil: "load" });
  await page.waitForTimeout(500);
  await page.screenshot({ path: path.join(__dirname, "test-mobile.png") });
  await browser.close();
  console.log("screenshots done");
})().catch(e => { console.error(e); process.exit(1); });
